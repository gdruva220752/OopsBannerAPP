/**
 * OOPSBannerApp - UC3 Implementation
 * Prints "OOPS" banner using String.join()
 * 
 * @author Nani
 * @version 3.0
 */
public class OOPSBannerApp {

    public static void main(String[] args) {

        System.out.println(String.join("   ",
                " ***** ", " ***** ", " ***** ", " ***** "));

        System.out.println(String.join("   ",
                "*     *", "*     *", "*     *", "*     *"));

        System.out.println(String.join("   ",
                "*     *", "*     *", "*     *", "*     *"));

        System.out.println(String.join("   ",
                "*     *", " ***** ", " ***** ", " ***** "));

        System.out.println(String.join("   ",
                "*     *", "*      ", "*            ", "     *"));

        System.out.println(String.join("   ",
                "*     *", "*      ", "*            ", "     *"));

        System.out.println(String.join("   ",
                " ***** ", "*      ", " ***** ", " ***** "));
    }
}
